cols = ["Country/Territory","Continent","Capital","CCA3","Area (km²)",
        "1970 Population","1980 Population","1990 Population","2000 Population",
        "2010 Population","2015 Population","2020 Population","2022 Population"]

df = pd.DataFrame(rows, columns=cols)

# Per-country annual growth rate, estimated from the 2020->2022 trend, used to
# project 2023-2026 forward from the 2022 figure (2026 is a mid-year estimate,
# since the current date is only partway through 2026).
_annual_rate = (df["2022 Population"] / df["2020 Population"]) ** (1 / 2)
for yr in [2023, 2024, 2025, 2026]:
    df[f"{yr} Population"] = (df["2022 Population"] * _annual_rate ** (yr - 2022)).round(0).astype("int64")

LATEST_YEAR = 2026
LATEST_COL = f"{LATEST_YEAR} Population"

# Growth Rate: CAGR over the most recent 2 years available, as a multiplier
# (e.g. 1.015 = +1.5%/yr), matching the format used by the well-known
# Kaggle "World Population Dataset".
df["Growth Rate"] = ((df[LATEST_COL] / df["2024 Population"]) ** (1 / 2)).round(4)

df["Density (per km²)"] = (df[LATEST_COL] / df["Area (km²)"]).round(2)

world_total = df[LATEST_COL].sum()
df["World Population Percentage"] = (df[LATEST_COL] / world_total * 100).round(2)

df = df.sort_values(LATEST_COL, ascending=False).reset_index(drop=True)
df.insert(0, "Rank", df.index + 1)

# reorder to a clean, conventional column order (most recent year first)
df = df[["Rank","CCA3","Country/Territory","Capital","Continent",
         "2026 Population","2025 Population","2024 Population","2023 Population",
         "2022 Population","2020 Population","2015 Population","2010 Population",
         "2000 Population","1990 Population","1980 Population","1970 Population",
         "Area (km²)","Density (per km²)","Growth Rate","World Population Percentage"]]

